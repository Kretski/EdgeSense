#!/usr/bin/env python3
"""
EdgeSense Nano: symbolic control-law extraction from logged data
Version: 2.1.0

Fits a closed-form equation   target = f(inputs)   directly to logged data
with PySR (symbolic regression), saves the full hall of fame, and exports the
selected equation as a plain C function.

Important: the regression target is a column of the CSV (by default `thrust`).
Earlier versions fitted the output of an *untrained* neural network instead of
the data, so equations produced by those versions do not describe the data and
must be regenerated with this script.

Usage:
    python scripts/train_on_real_data.py
    python scripts/train_on_real_data.py --csv data/pool_record.csv \
        --inputs error gyro_y --target thrust --seed 42
"""
import argparse
import os
import re
import sys

import numpy as np
import pandas as pd

C_ARGS = ["x0", "x1", "x2"]  # fixed signature used by MainDemo.ino


def parse_args():
    p = argparse.ArgumentParser(description="EdgeSense symbolic control-law extraction")
    p.add_argument("--csv", default=os.path.join("data", "pool_record.csv"),
                   help="input CSV with logged data")
    p.add_argument("--inputs", nargs="+", default=["error", "gyro_y"],
                   help="input columns (at most 3; mapped to x0, x1, x2 in order)")
    p.add_argument("--target", default="thrust",
                   help="column to predict (the actuator command)")
    p.add_argument("--iterations", type=int, default=50, help="PySR iterations")
    p.add_argument("--seed", type=int, default=42, help="random seed")
    p.add_argument("--test-fraction", type=float, default=0.2,
                   help="fraction of rows held out for evaluation (taken from the end)")
    p.add_argument("--out-dir", default="outputs", help="output directory")
    p.add_argument("--model-name", default="real_physics_model",
                   help="C function name prefix")
    p.add_argument("--data-label", default="UNSPECIFIED",
                   help="provenance written into the C header, e.g. SIMULATED or HARDWARE")
    return p.parse_args()


def to_c_expression(equation_str: str) -> str:
    """Convert a sympy-style expression string to C (float literals, math.h names)."""
    eq = equation_str
    eq = re.sub(r"\bsqrt\b", "sqrtf", eq)
    eq = re.sub(r"\bexp\b", "expf", eq)
    eq = re.sub(r"\bsin\b", "sinf", eq)
    eq = re.sub(r"\bcos\b", "cosf", eq)
    eq = eq.replace("**", "^POW^")
    if "^POW^" in eq:
        raise ValueError(f"Power operator not supported in C export: {equation_str}")
    # float suffix on decimal literals (including exponent form), not inside identifiers
    eq = re.sub(r"(?<![\w.])(\d+\.\d*(?:[eE][+-]?\d+)?|\d+[eE][+-]?\d+)(?![\w.])", r"\1f", eq)
    return eq


def export_to_c(equation_str: str, input_names, target_name: str,
                model_name: str, data_label: str, source_csv: str) -> str:
    """Generate the C function. Unused arguments are explicitly cast to void."""
    c_expr = to_c_expression(equation_str)
    mapping = ", ".join(f"{C_ARGS[i]} = {name}" for i, name in enumerate(input_names))
    used = set(re.findall(r"\bx[0-2]\b", c_expr))
    void_lines = "".join(f"    (void){a};\n" for a in C_ARGS if a not in used)

    return f"""/* GENERATED BY EDGESENSE NANO v2.1
 * Symbolic regression fit: {target_name} = f({", ".join(input_names)})
 * Data source: {source_csv}
 * Data type:   {data_label}
 * Inputs:      {mapping}
 * This is a fitted expression, not a derived physical law.
 */
#include <math.h>

float {model_name}_inference(float x0, float x1, float x2) {{
{void_lines}    return {c_expr};
}}
"""


def main():
    args = parse_args()

    if not 1 <= len(args.inputs) <= 3:
        sys.exit("Error: --inputs must name between 1 and 3 columns.")
    if args.target in args.inputs:
        sys.exit("Error: the target column must not also be an input.")

    if not os.path.exists(args.csv):
        sys.exit(f"Error: file not found: {args.csv}\n"
                 f"Expected columns: {', '.join(args.inputs + [args.target])}")

    df = pd.read_csv(args.csv)
    missing = [c for c in args.inputs + [args.target] if c not in df.columns]
    if missing:
        sys.exit(f"Error: missing columns in {args.csv}: {missing}")

    df = df[args.inputs + [args.target]].dropna()
    X = df[args.inputs].to_numpy(dtype=np.float64)
    y = df[args.target].to_numpy(dtype=np.float64)
    print(f"Loaded {len(df)} rows from {args.csv}")

    # Chronological split: no shuffling, so the test set is genuinely unseen
    n_test = int(round(len(df) * args.test_fraction))
    if n_test < 1 or len(df) - n_test < 10:
        sys.exit("Error: not enough rows for a train/test split.")
    X_train, X_test = X[:-n_test], X[-n_test:]
    y_train, y_test = y[:-n_test], y[-n_test:]

    from pysr import PySRRegressor  # imported here so --help works without Julia

    feature_names = C_ARGS[:len(args.inputs)]
    model = PySRRegressor(
        niterations=args.iterations,
        populations=8,
        binary_operators=["+", "-", "*"],
        unary_operators=["exp", "sqrt"],
        maxsize=12,
        parsimony=0.01,
        model_selection="best",
        random_state=args.seed,
        deterministic=True,
        parallelism="serial",
        verbosity=0,
    )
    print("Running symbolic regression...")
    model.fit(X_train, y_train, variable_names=feature_names)

    os.makedirs(args.out_dir, exist_ok=True)
    hof_path = os.path.join(args.out_dir, "hall_of_fame.csv")
    model.equations_.to_csv(hof_path, index=False)

    equation = str(model.sympy())
    y_hat = model.predict(X_test)
    rmse = float(np.sqrt(np.mean((y_test - y_hat) ** 2)))
    baseline = float(np.sqrt(np.mean((y_test - y_train.mean()) ** 2)))
    ss_res = float(np.sum((y_test - y_hat) ** 2))
    ss_tot = float(np.sum((y_test - y_test.mean()) ** 2))
    r2 = 1.0 - ss_res / ss_tot if ss_tot > 0 else float("nan")

    print(f"\nSelected equation: {args.target} = {equation}")
    print(f"Held-out RMSE: {rmse:.5g}  (constant-mean baseline: {baseline:.5g})")
    print(f"Held-out R^2:  {r2:.4f}")
    print(f"Hall of fame:  {hof_path}")

    c_code = export_to_c(equation, args.inputs, args.target, args.model_name,
                         args.data_label, args.csv)
    c_path = os.path.join(args.out_dir, f"{args.model_name}.c")
    with open(c_path, "w", encoding="utf-8") as f:
        f.write(c_code)
    print(f"C code:        {c_path}")


if __name__ == "__main__":
    main()
